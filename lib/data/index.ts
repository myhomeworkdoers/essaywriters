export function getOrCreateKeywordData(slug: string, queryKeyword?: string): KeywordData {
  const normalizedSlug = slug.toLowerCase().trim();
  const existing = keywordsData[normalizedSlug];
  if (existing) {
    // If search param keyword was explicitly passed and differs, we can customize keyword/h1/title
    if (queryKeyword && queryKeyword.trim() && queryKeyword.toLowerCase() !== existing.keyword.toLowerCase()) {
      const customKw = queryKeyword.trim();
      return {
        ...existing,
        keyword: customKw,
        h1: `Can You ${customKw.charAt(0).toUpperCase() + customKw.slice(1)}?`,
        title: `${customKw.charAt(0).toUpperCase() + customKw.slice(1)} | Zero-AI & 100% Plagiarism-Free (2026)`,
      };
    }
    return existing;
  }

  // Fallback generation for any custom route or search query
  const rawKeyword = queryKeyword && queryKeyword.trim() 
    ? queryKeyword.trim() 
    : normalizedSlug.replace(/[-_]+/g, ' ').trim();
  
  const displayKeyword = rawKeyword.toLowerCase();
  const capitalizedKeyword = displayKeyword.charAt(0).toUpperCase() + displayKeyword.slice(1);
  const baseTemplate = pay_someone_to_write_my_essay;

  return {
    ...baseTemplate,
    slug: normalizedSlug,
    keyword: displayKeyword,
    title: `${capitalizedKeyword} | Zero-AI & 100% Plagiarism-Free (2026)`,
    metaDescription: `Looking to ${displayKeyword}? Work with verified US, UK, AU & Canadian Master's/PhD academic writers. 100% human research, Turnitin-safe, zero AI, and 24/7 direct chat.`,
    h1: `Can You ${capitalizedKeyword}?`,
    subheading: `Connect with accredited subject-matter scholars for custom research, academic formatting, and zero-AI writing tailored to US, UK, Australian, and Canadian university rubrics.`,
    badge: `Verified Academic Excellence • 2026 Edition`,
  };
}
